# -*- coding: utf-8 -*-
"""Expand the annotation set with chips that actually show a river channel.

Two corrections requested after the first 16 masks were reviewed:

1. Dry MINING chips (NDSI water fraction < 0.02) have no visible river, so no
   extraction damage can be confirmed at pixel level. Their annotation hint is
   changed to UNSURE and the empty mask is kept. The original chip-level label
   in ``verified_labels.csv`` is NOT overwritten; the change is recorded in
   ``annotation/label_overrides.csv`` and applies to this segmentation subset
   only.

2. More chips with visible water are added (from labels MINING / UNSURE first,
   then NOT MINING) so the annotator can see the channel and paint damage.

Water overlays for every chip are regenerated by ``09_generate_water_overlay``.
"""
from __future__ import annotations

import csv
import json
import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))
import config.project_config as cfg  # noqa: E402
import importlib.util  # noqa: E402

ROOT = cfg.WORKSPACE_ROOT / "annotation"
CHIPS_JSON = ROOT / "chips.json"
IMAGES = ROOT / "images"
OVERRIDES = ROOT / "label_overrides.csv"
LABELS = cfg.WORKSPACE_ROOT / "label_review" / "verified_labels.csv"
FEATURES = cfg.WORKSPACE_ROOT / "extra_features" / "chip_features.csv"

DRY_WATER_THRESHOLD = 0.02   # below this fraction the channel is not visible
N_RIVER_FROM_POSITIVE = 8    # MINING + UNSURE chips with water
N_RIVER_FROM_NEGATIVE = 4    # NOT MINING chips with water
MIN_WATER_POSITIVE = 0.02
MIN_WATER_NEGATIVE = 0.05
LABEL_PRIORITY = {"MINING": 0, "UNSURE": 1, "NOT MINING": 2}


def read_csv(path: Path) -> list[dict]:
    with path.open(encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def load_overlay_module():
    spec = importlib.util.spec_from_file_location(
        "water_overlay", REPO / "src" / "labeling" / "09_generate_water_overlay.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main() -> int:
    entries = json.loads(CHIPS_JSON.read_text(encoding="utf-8"))
    features = {r["chip_id"]: r for r in read_csv(FEATURES)}
    labels = {r["chip_id"]: r for r in read_csv(LABELS)}
    existing = {e["chip_id"] for e in entries}
    used_transects = {e["transect_id"] for e in entries}

    # ---- 1. re-label dry MINING chips in the annotation subset -------------
    overrides = []
    for e in entries:
        wf = float(features.get(e["chip_id"], {}).get("water_frac", 0.0))
        e["water_frac"] = round(wf, 4)
        if e["label_hint"] == "MINING" and wf < DRY_WATER_THRESHOLD:
            overrides.append({
                "chip_id": e["chip_id"],
                "original_label": e["label_hint"],
                "new_label": "UNSURE",
                "water_frac": round(wf, 4),
                "reason": "no visible river/channel in chip; empty human mask cannot confirm extraction",
            })
            e["label_hint"] = "UNSURE"
            e["label_override"] = True
    with OVERRIDES.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["chip_id", "original_label", "new_label",
                                          "water_frac", "reason"])
        w.writeheader()
        w.writerows(overrides)
    print(f"re-labelled {len(overrides)} dry MINING chips -> UNSURE")

    # ---- 2. rank candidate river chips ------------------------------------
    def candidates(min_water: float, wanted_labels: set[str]) -> list[dict]:
        out = []
        for cid, r in labels.items():
            if cid in existing or r["reviewer_final_label"] not in wanted_labels:
                continue
            wf = float(features.get(cid, {}).get("water_frac", 0.0))
            if wf < min_water:
                continue
            out.append({
                "chip_id": cid,
                "quarter": r["quarter"],
                "transect_id": r["transect_id"],
                "label_hint": r["reviewer_final_label"],
                "sand_frac": float(r["sand_frac"]),
                "water_frac": round(wf, 4),
                "new_transect": r["transect_id"] not in used_transects,
            })
        out.sort(key=lambda x: (not x["new_transect"],
                                LABEL_PRIORITY.get(x["label_hint"], 9),
                                -x["water_frac"]))
        return out

    pos = candidates(MIN_WATER_POSITIVE, {"MINING", "UNSURE"})
    neg = candidates(MIN_WATER_NEGATIVE, {"NOT MINING"})
    picked, picked_ids = [], set()
    for pool, n in ((pos, N_RIVER_FROM_POSITIVE), (neg, N_RIVER_FROM_NEGATIVE)):
        taken = 0
        # first pass: new transects only (keeps GroupKFold groups independent)
        for prefer_new in (True, False):
            for c in pool:
                if taken >= n:
                    break
                if c["chip_id"] in picked_ids:
                    continue
                # Pass 1 prefers unseen transects. Pass 2 allows reuse: chips
                # sharing a transect simply land in the same GroupKFold fold,
                # which is leak-free and still gives >20 independent groups.
                if prefer_new and c["transect_id"] in used_transects:
                    continue
                c["new_transect"] = c["transect_id"] not in used_transects
                picked.append(c)
                picked_ids.add(c["chip_id"])
                used_transects.add(c["transect_id"])
                taken += 1
            if taken >= n:
                break
        if taken < n:
            print(f"WARN wanted {n} river chips, found {taken}")

    # ---- 3. copy previews and append entries -------------------------------
    IMAGES.mkdir(parents=True, exist_ok=True)
    for c in picked:
        for suffix in ("truecolour", "NDSI"):
            src = cfg.CHIPS_FIXED_DIR / c["quarter"] / "previews" / f"{c['chip_id']}_{suffix}.png"
            if src.exists():
                shutil.copy2(src, IMAGES / f"{c['chip_id']}_{suffix}.png")
            else:
                print("MISSING preview:", src)
        c["selection_reason"] = "river_chip"
        entries.append(c)
        print("ADD", c["chip_id"], c["label_hint"], "water=%.4f" % c["water_frac"],
              "new_transect" if c["new_transect"] else "reused transect")

    CHIPS_JSON.write_text(json.dumps(entries, indent=2), encoding="utf-8")

    # ---- 4. regenerate water overlays for the whole annotation set ---------
    mod = load_overlay_module()
    mod.main()

    print(f"TOTAL annotation chips: {len(entries)} "
          f"({sum(e['label_hint']=='MINING' for e in entries)} MINING, "
          f"{sum(e['label_hint']=='NOT MINING' for e in entries)} NOT MINING, "
          f"{sum(e['label_hint']=='UNSURE' for e in entries)} UNSURE)")
    print("overrides:", OVERRIDES)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
